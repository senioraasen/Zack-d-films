#!/usr/bin/env python3
"""Build the voiceover and the edit timeline from one audio file per script line.

Usage (from the project folder):  python3 tools/timeline.py
Reads  script.json (list of sentences) and audio/lines/<n>.mp3 (n = 1..N).
Writes audio/vo.wav, audio.m4a (preview) and src/timeline.js with LINES, CAPTIONS and DURATION.

Word times are estimated: each line is split at its pauses (found with ffmpeg
silencedetect) and words are spread over each spoken stretch by length.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

GAP = 0.22          # pause between lines
LEAD = 0.35         # silence before the first line
TAIL = 1.2          # room after the last line
EXTRA_GAP = {3: 0.45}  # longer pause before line 3 (the "Men" turn)


def dur(p):
    return float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)]))


def speech_spans(p, total):
    out = subprocess.run(["ffmpeg", "-i", str(p), "-af", "silencedetect=n=-38dB:d=0.12", "-f", "null", "-"],
                         capture_output=True, text=True).stderr
    starts = [float(x) for x in re.findall(r"silence_start: ([0-9.]+)", out)]
    ends = [float(x) for x in re.findall(r"silence_end: ([0-9.]+)", out)]
    sil = list(zip(starts, ends + [total] * (len(starts) - len(ends))))
    spans, cur = [], 0.0
    for s, e in sil:
        if s - cur > 0.05:
            spans.append([cur, s])
        cur = e
    if total - cur > 0.05:
        spans.append([cur, total])
    return spans


def chunk_words(words):
    """1-3 word captions, breaking after punctuation and keeping short words together."""
    MAXC = 13
    out, cur = [], []
    for i, w in enumerate(words):
        nxt = words[i + 1]["w"] if i + 1 < len(words) else ""
        cand = " ".join(x["w"] for x in cur + [w])
        if cur and (len(cand) > MAXC or len(cur) == 3):
            out.append(cur)
            cur = []
        cur.append(w)
        text = " ".join(x["w"] for x in cur)
        short = len(re.sub(r"\W", "", w["w"])) <= 2
        # Break after punctuation, but keep tiny words (i, å, et, en) with the next word.
        if re.search(r"[,.?!:]$", w["w"]) or (not short and nxt and len(text + " " + nxt) > MAXC):
            out.append(cur)
            cur = []
    if cur:
        if out and len(" ".join(x["w"] for x in cur)) <= 2:
            out[-1] += cur
        else:
            out.append(cur)
    return out


def main():
    root = Path(__file__).resolve().parent.parent
    lines = json.loads((root / "script.json").read_text())
    t = LEAD
    LINES, CAPS, parts = [], [], []
    for n, text in enumerate(lines, 1):
        f = root / "audio" / "lines" / f"{n}.mp3"
        d = dur(f)
        t += EXTRA_GAP.get(n, 0)
        spans = speech_spans(f, d)
        clauses = [c.strip() for c in re.split(r"(?<=[,.?!])\s+", text) if c.strip()]
        if len(spans) != len(clauses):
            spans = [[spans[0][0], spans[-1][1]]] if spans else [[0, d]]
            clauses = [text]
        words = []
        for (s, e), clause in zip(spans, clauses):
            ws = clause.split()
            weights = [len(re.sub(r"[^\wæøåÆØÅ]", "", w)) + 1.5 for w in ws]
            tot, acc = sum(weights), 0.0
            for w, wt in zip(ws, weights):
                a = s + (e - s) * acc / tot
                acc += wt
                b = s + (e - s) * acc / tot
                words.append({"w": w, "start": round(t + a, 3), "end": round(t + b, 3)})
        LINES.append({"n": n, "text": text, "start": round(t, 3), "end": round(t + d, 3), "words": words})
        for c in chunk_words(words):
            label = " ".join(x["w"] for x in c).rstrip(",.").upper()
            CAPS.append([c[0]["start"], label, round(c[-1]["end"] + 0.12, 3)])
        parts.append((f, t))
        t += d + GAP
    total = round(t - GAP + TAIL, 2)

    # Mix every line at its start time into one mono wav.
    inputs, filt = [], []
    for i, (f, start) in enumerate(parts):
        inputs += ["-i", str(f)]
        ms = int(start * 1000)
        filt.append(f"[{i}:a]aresample=44100,adelay={ms}|{ms}[a{i}]")
    filt.append("".join(f"[a{i}]" for i in range(len(parts))) + f"amix=inputs={len(parts)}:normalize=0,apad,atrim=0:{total}[out]")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *inputs, "-filter_complex", ";".join(filt),
                    "-map", "[out]", "-ac", "1", "-ar", "44100", str(root / "audio" / "vo.wav")], check=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(root / "audio" / "vo.wav"), "-c:a", "aac", "-b:a", "160k",
                    str(root / "audio.m4a")], check=True)

    js = ["// Generated by tools/timeline.py: do not edit by hand.",
          f"export const DURATION = {total};",
          "export const LINES = " + json.dumps(LINES, ensure_ascii=False, indent=1) + ";",
          "export const CAPTIONS = " + json.dumps(CAPS, ensure_ascii=False) + ";", ""]
    (root / "src" / "timeline.js").write_text("\n".join(js))
    for L in LINES:
        print(f'{L["n"]}: {L["start"]:6.2f}-{L["end"]:6.2f}  {L["text"]}')
    print("captions:", " | ".join(f"{c[0]:.2f} {c[1]}" for c in CAPS))
    print("DURATION", total)


if __name__ == "__main__":
    sys.exit(main())
